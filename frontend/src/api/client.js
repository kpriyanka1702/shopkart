import axios from 'axios';

const api = axios.create({
  baseURL: import.meta.env.VITE_API_BASE_URL || '/api',
});

api.interceptors.request.use((config) => {
  const token = localStorage.getItem('token');
  if (token) {
    config.headers.Authorization = `Bearer ${token}`;
  }
  return config;
});

api.interceptors.response.use(
  (response) => response,
  (error) => {
    const status = error.response?.status;
    // A stale/expired/invalid JWT surfaces as 401 or 403. If we sent a token
    // and got rejected, clear it and send the user to login instead of
    // leaving them stuck on a Forbidden error.
    const hadToken = Boolean(error.config?.headers?.Authorization);
    if ((status === 401 || status === 403) && hadToken) {
      localStorage.removeItem('token');
      localStorage.removeItem('user');
      if (window.location.pathname !== '/login') {
        window.location.assign('/login');
      }
    }
    return Promise.reject(error);
  }
);

export default api;
